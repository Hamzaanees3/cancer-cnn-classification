import os
import numpy as np
import shutil
from sklearn.model_selection import train_test_split
import tensorflow as tf
from tensorflow.keras.preprocessing.image import ImageDataGenerator

# Define directory paths
base_dataset_dir = '/content/dataset/train_cancer'
split_base_dir = '/content/dataset_split'
train_dir = os.path.join(split_base_dir, 'train')
val_dir = os.path.join(split_base_dir, 'val')
test_dir = os.path.join(split_base_dir, 'test')

classes = ['benign', 'malignant']

# Create train/val/test subdirectories
for split in [train_dir, val_dir, test_dir]:
    for cls in classes:
        os.makedirs(os.path.join(split, cls), exist_ok=True)

# Collect all image file paths and labels
file_paths = []
labels = []

for cls in classes:
    cls_path = os.path.join(base_dataset_dir, cls)
    for img_name in os.listdir(cls_path):
        if img_name.lower().endswith(('.png', '.jpg', '.jpeg')):
            file_paths.append(os.path.join(cls_path, img_name))
            labels.append(cls)

# Stratified Train-Validation-Test Split (70-15-15)
train_files, temp_files, train_labels, temp_labels = train_test_split(
    file_paths, labels, test_size=0.30, random_state=42, stratify=labels
)

val_files, test_files, val_labels, test_labels = train_test_split(
    temp_files, temp_labels, test_size=0.50, random_state=42, stratify=temp_labels
)

# Helper function to copy images to respective split folders
def copy_images(files, labels, dest_root_dir):
    for file_path, label in zip(files, labels):
        dest_path = os.path.join(dest_root_dir, label, os.path.basename(file_path))
        shutil.copy(file_path, dest_path)

# Copy the split files
copy_images(train_files, train_labels, train_dir)
copy_images(val_files, val_labels, val_dir)
copy_images(test_files, test_labels, test_dir)

print("Dataset splits created successfully:")
print(f"- Train Set: {len(train_files)} images")
print(f"- Validation Set: {len(val_files)} images")
print(f"- Test Set: {len(test_files)} images")

# Define constants for image preprocessing
IMG_SIZE = (224, 224)
BATCH_SIZE = 16

# Set up ImageDataGenerators for image loading and normalization
train_datagen = ImageDataGenerator(rescale=1./255)
val_datagen = ImageDataGenerator(rescale=1./255)
test_datagen = ImageDataGenerator(rescale=1./255)

train_generator = train_datagen.flow_from_directory(
    train_dir,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='binary',
    shuffle=True
)

val_generator = val_datagen.flow_from_directory(
    val_dir,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='binary',
    shuffle=False
)

test_generator = test_datagen.flow_from_directory(
    test_dir,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='binary',
    shuffle=False
)

import tensorflow as tf
from tensorflow.keras import layers, models
import matplotlib.pyplot as plt

# 1. Build the CNN Model Architecture
def build_cnn_model(input_shape=(224, 224, 3)):
    model = models.Sequential([
        # First Convolutional Block
        layers.Conv2D(32, (3, 3), activation='relu', input_shape=input_shape),
        layers.BatchNormalization(),
        layers.MaxPooling2D((2, 2)),
        layers.Dropout(0.25),

        # Second Convolutional Block
        layers.Conv2D(64, (3, 3), activation='relu'),
        layers.BatchNormalization(),
        layers.MaxPooling2D((2, 2)),
        layers.Dropout(0.25),

        # Third Convolutional Block
        layers.Conv2D(128, (3, 3), activation='relu'),
        layers.BatchNormalization(),
        layers.MaxPooling2D((2, 2)),
        layers.Dropout(0.3),

        # Flatten & Dense Layers
        layers.Flatten(),
        layers.Dense(128, activation='relu'),
        layers.BatchNormalization(),
        layers.Dropout(0.5),
        layers.Dense(1, activation='sigmoid')  # Sigmoid output for binary classification
    ])

    return model

model = build_cnn_model()

# Compile the model
model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=0.001),
    loss='binary_crossentropy',
    metrics=['accuracy']
)

model.summary()

# 2. Train the Model
# Since our dataset is relatively small, 15-20 epochs are a good starting point to prevent severe overfitting.
EPOCHS = 20

history = model.fit(
    train_generator,
    epochs=EPOCHS,
    validation_data=val_generator,
    verbose=1
)

# Save the trained model in Keras native format
model_save_path = 'cancer_cnn_model.keras'
model.save(model_save_path)
print(f"\nModel successfully saved to {model_save_path}")

import numpy as np
from sklearn.metrics import classification_report, confusion_matrix
import seaborn as sns

# 3. Create Training Accuracy and Loss Graphs
def plot_training_history(history):
    acc = history.history['accuracy']
    val_acc = history.history['val_accuracy']
    loss = history.history['loss']
    val_loss = history.history['val_loss']
    epochs_range = range(1, len(acc) + 1)

    plt.figure(figsize=(14, 5))

    # Plot Accuracy
    plt.subplot(1, 2, 1)
    plt.plot(epochs_range, acc, label='Training Accuracy', marker='o')
    plt.plot(epochs_range, val_acc, label='Validation Accuracy', marker='x')
    plt.title('Training and Validation Accuracy')
    plt.xlabel('Epochs')
    plt.ylabel('Accuracy')
    plt.legend(loc='lower right')
    plt.grid(True)

    # Plot Loss
    plt.subplot(1, 2, 2)
    plt.plot(epochs_range, loss, label='Training Loss', marker='o')
    plt.plot(epochs_range, val_loss, label='Validation Loss', marker='x')
    plt.title('Training and Validation Loss')
    plt.xlabel('Epochs')
    plt.ylabel('Loss')
    plt.legend(loc='upper right')
    plt.grid(True)

    plt.tight_layout()
    plt.show()

plot_training_history(history)

# 4. Model Evaluation using Test Dataset
print("\n--- Evaluating Model on Test Dataset ---")
test_loss, test_accuracy = model.evaluate(test_generator, verbose=0)
print(f"Test Loss: {test_loss:.4f}")
print(f"Test Accuracy: {test_accuracy:.4f}")

# Generate predictions for classification metrics
test_generator.reset()
Y_pred = model.predict(test_generator)
y_pred = (Y_pred > 0.5).astype(int).flatten()
y_true = test_generator.classes

